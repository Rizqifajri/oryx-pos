/**
 * Regenerates docs/api.md from the controllers, so the route list can't drift
 * from the code the way the old hand-written BACKEND_API.md did.
 *
 * Usage (from apps/api):  npx tsx src/scripts/gen-api-docs.ts
 */
import fs from "node:fs";
import path from "node:path";

const SRC = path.resolve(__dirname, "../modules");
const OUT = path.resolve(__dirname, "../../../../docs/api.md");

type Route = { method: string; path: string; access: string };

const walk = (dir: string): string[] =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(path.join(dir, e.name)) : e.name.endsWith(".controller.ts") ? [path.join(dir, e.name)] : [],
  );

const routesOf = (file: string): { module: string; routes: Route[] }[] => {
  const src = fs.readFileSync(file, "utf8");
  // A file can hold several controllers (e.g. sessions + service-requests).
  const chunks = src.split(/(?=@Controller\()/);
  return chunks.flatMap((chunk, i) => {
    const base = chunk.match(/@Controller\(\s*["'`]([^"'`]*)["'`]/)?.[1];
    if (base === undefined) return [];
    // A class-level @Public() sits just before @Controller, i.e. at the end of the previous chunk.
    const classPublic = i > 0 && /@Public\(\)\s*$/.test(chunks[i - 1] ?? "");
    const routes: Route[] = [];
    const re = /((?:\s*@\w+\([^)]*\))*?)\s*@(Get|Post|Patch|Put|Delete|Sse)\(\s*(?:["'`]([^"'`]*)["'`])?\s*\)((?:\s*@\w+\([^)]*\))*)/g;
    for (const m of chunk.matchAll(re)) {
      const decorators = `${m[1]} ${m[4]}`;
      const perms = decorators.match(/@RequirePermissions\(([^)]*)\)/)?.[1]?.match(/["'][^"']+["']/g)?.map((p) => `\`${p.slice(1, -1)}\``);
      const access = perms
        ? perms.join(" or ")
        : /GuestSessionGuard/.test(decorators)
          ? "guest token"
          : classPublic || /@Public\(\)/.test(decorators)
            ? "public"
            : "any signed-in user";
      routes.push({ method: m[2] === "Sse" ? "GET (SSE)" : (m[2] ?? "").toUpperCase(), path: `/${[base, m[3]].filter(Boolean).join("/")}`, access });
    }
    return routes.length ? [{ module: base, routes }] : [];
  });
};

const groups = walk(SRC).sort().flatMap(routesOf);
const total = groups.reduce((n, g) => n + g.routes.length, 0);

const lines = [
  "# API reference",
  "",
  "<!-- Generated by apps/api/src/scripts/gen-api-docs.ts — do not edit by hand. -->",
  "",
  `${total} routes. Base URL: \`/api/v1\`. Request bodies are validated by the Zod schema in each module's \`*.schema.ts\`; that file is the source of truth for field names and limits.`,
  "",
  "**Access** column:",
  "- a permission (e.g. `menu:list`) — staff bearer token whose role holds it; several mean *any one of them*. GLOBAL (super-admin) users pass every permission check.",
  "- `any signed-in user` — staff bearer token, no specific permission.",
  "- `guest token` — the guest session token issued when a QR table session is opened.",
  "- `public` — no authentication.",
  "",
  "Every response is `{ \"success\": true, \"data\": … }` or `{ \"success\": false, \"message\": \"…\" }` with an HTTP error status.",
  "",
];
for (const g of groups) {
  lines.push(`## \`/${g.module}\``, "", "| Method | Path | Access |", "| --- | --- | --- |");
  for (const r of g.routes) lines.push(`| ${r.method} | \`${r.path}\` | ${r.access} |`);
  lines.push("");
}

fs.writeFileSync(OUT, lines.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), OUT)} — ${total} routes in ${groups.length} groups`);
